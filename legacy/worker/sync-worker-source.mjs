import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const root = resolve(new URL('..', import.meta.url).pathname);
const sourcePath = resolve(root, 'omniwall.txt');
const targetPath = resolve(root, 'src/worker.mjs');

const source = readFileSync(sourcePath, 'utf8');
if (!source.includes('export default')) {
  throw new Error('omniwall.txt must contain an ESM export default Worker object');
}

const banner = `// Generated by scripts/sync-worker-source.mjs from omniwall.txt.\n// Edit omniwall.txt, then run npm run sync:worker.\n\n`;
mkdirSync(dirname(targetPath), { recursive: true });
writeFileSync(targetPath, banner + source, 'utf8');
console.log(`Synced omniwall.txt -> src/worker.mjs (${source.length} bytes)`);
